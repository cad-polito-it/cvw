#!/usr/bin/env python3
"""Server-side launchers for Part 2. Requires Python 3.6+; standard library only."""

import argparse
from datetime import datetime, timezone
import hashlib
import json
import math
import os
from pathlib import Path
import re
import shlex
import shutil
import subprocess
import sys
import time

ROOT = Path(__file__).resolve().parents[1]
TB = ROOT / "testbench"
ZOIX = ROOT / "zoix"
RUN = ROOT / "run"
CONFIG = "syn_polito_rv32e"
# Course derivative, kept out of config/derivlist.txt so upstream merges stay clean.
DERIVLIST = ROOT / "config" / "derivlist_polito.txt"
GATE = ROOT / "gate" / CONFIG
NETLIST = GATE / "wallypipelinedcore.sv"
LIBRARY = GATE / "techLib.v"
# The Nangate45 files are not redistributed in this repository. Copy them into
# lib/ or set CVW_SYNTH_DB / LIBRARY_SIM_PATH; the server copy is the fallback.
LIB_DIRS = (ROOT / "lib", Path("/data/libraries/nangate45"))
DB_NAME = "NangateOpenCellLibrary_typical.db"
MODEL_NAME = "NangateOpenCellLibrary.v"


def rel(path):
    """Record paths inside the checkout relative to it, so a moved folder stays valid."""
    path = Path(path).resolve()
    try:
        return path.relative_to(ROOT).as_posix()
    except ValueError:
        return str(path)


def find_library(variable, name, preferred=None):
    if os.environ.get(variable):
        return Path(os.environ[variable])
    candidates = ([preferred] if preferred else []) + [folder / name for folder in LIB_DIRS]
    for candidate in candidates:
        if candidate.is_file():
            return candidate
    return candidates[0]  # require_file() then reports the expected location


def ignore_folder(folder):
    """Generated folders carry their own .gitignore; the upstream one is untouched."""
    folder.mkdir(parents=True, exist_ok=True)
    marker = folder / ".gitignore"
    if not marker.exists():
        marker.write_text("# Generated by bin/run_cvw.py\n*\n")


def require_file(path):
    if not path.is_file():
        raise RuntimeError(f"Missing file: {path}")
    return path


def require_tools(*names):
    for name in names:
        if shutil.which(name) is None:
            raise RuntimeError(f"{name} is not on PATH. Activate the server's EDA environment first.")


def run(command, cwd, log, extra_env=None):
    """Stream and save output, and propagate failures (no shell or pipelines)."""
    display_command = " ".join(shlex.quote(str(arg)) for arg in command)
    print(f"\n[{cwd}] {display_command}", flush=True)
    start = time.monotonic()
    environment = os.environ.copy()
    environment.setdefault("MTI_VCO_MODE", "64")
    if extra_env:
        environment.update({name: str(value) for name, value in extra_env.items()})
    with log.open("w") as stream:
        process = subprocess.Popen([str(arg) for arg in command], cwd=cwd,
                                   stdout=subprocess.PIPE, stderr=subprocess.STDOUT,
                                   universal_newlines=True, errors="replace", env=environment)
        for line in process.stdout:
            print(line, end="", flush=True)
            stream.write(line)
        status = process.wait()
        stream.write(f"\nLauncher elapsed seconds: {time.monotonic() - start:.3f}\n")
    if status:
        raise RuntimeError(f"Command exited with status {status}; see {log}")


def write_config():
    """Generate just the supplied derivative, leaving config/deriv untouched.

    Matches derivgen.pl's parameter substitutions for this direct rv32e
    derivative. Reject changes to its inheritance rather than guessing.
    """
    lines = DERIVLIST.read_text().splitlines()
    overrides = {}
    found = False
    for line in lines:
        fields = line.split("#", 1)[0].split()
        if not fields:
            continue
        if fields[0] in ("deriv", "derive"):
            if found:
                break
            if fields[1] == CONFIG:
                if fields[2:] != ["rv32e"]:
                    raise RuntimeError("The selected derivative must inherit directly from rv32e")
                found = True
        elif found:
            overrides[fields[0]] = " ".join(fields[1:])
    if not found:
        raise RuntimeError(f"{CONFIG} not found in {rel(DERIVLIST)}")
    content = (ROOT / "config" / "rv32e" / "config.vh").read_text()
    for name, value in overrides.items():
        pattern = rf"(\b{re.escape(name)}\s*=\s*)[^;]*;"
        content, count = re.subn(pattern, lambda match: match[1] + value + ";", content)
        if count != 1:
            raise RuntimeError(f"Expected exactly one definition of {name}; found {count}")
    ignore_folder(RUN)
    folder = RUN / "config"
    folder.mkdir(parents=True, exist_ok=True)
    path = folder / "config.vh"
    path.write_text(f"// Generated derivative: {CONFIG}; sourced from {rel(DERIVLIST)}\n" + content)
    return folder


def source_files(mode):
    files = [ROOT / "src" / "cvw.sv"]
    if mode == "gate":
        files += [require_file(LIBRARY), require_file(NETLIST)]
    else:
        # Same SRAM macro exclusions as the repository's VCS launcher.
        excluded = {"rom1p1r_128x64.sv", "rom1p1r_128x32.sv",
                    "ram2p1r1wbe_128x64.sv", "ram2p1r1wbe_2048x64.sv"}
        files += [path for path in sorted((ROOT / "src").rglob("*.sv"))
                  if path != files[0] and path.name not in excluded]
    return files + [TB / "cvw_tb.sv"]


def build(mode, simulator):
    if mode == "gate":
        validate_synthesized_gate()
    config = write_config()
    folder = RUN / simulator / f"build_{mode}"
    folder.mkdir(parents=True, exist_ok=True)
    includes = [f"+incdir+{config}", f"+incdir+{ROOT / 'config' / 'shared'}"]
    defines = ["+define+functional"]
    if mode == "gate":
        defines.append("+define+CVW_GATE")
    files = source_files(mode)
    if simulator == "questa":
        require_tools("vlib", "vlog", "vsim")
        work = folder / "work"
        if not work.exists():
            run(["vlib", work], folder, folder / "vlib.log")
        run(["vlog", "-sv", "-work", work, "-timescale", "1ns/1ps",
             *includes, *defines, *files], folder, folder / "compile.log")
    else:
        require_tools("vcs")
        run(["vcs", "-full64", "-sverilog", "-timescale=1ns/1ps",
             "-debug_access+all", "-debug_region+cell", "+notimingcheck",
             "-top", "cvw_tb", *includes, *defines, *files,
             "-o", folder / "simv"], folder, folder / "compile.log")
    return folder


def digest(path):
    return hashlib.sha256(require_file(path).read_bytes()).hexdigest()


def synthesis_inputs():
    files = source_files("rtl")[:-1]
    files += [path for path in sorted((ROOT / "src").rglob("*"))
              if path.is_file() and path.suffix in (".vh", ".svh")]
    files += [DERIVLIST, ROOT / "config" / "rv32e" / "config.vh"]
    files += sorted((ROOT / "config" / "shared").glob("*.vh"))
    files += [ROOT / "synthDC" / "scripts" / name
              for name in ("cvw_wrapper.sv", "cvw_synth.tcl")]
    return {path.relative_to(ROOT).as_posix(): digest(path) for path in files}


def validate_synthesized_gate():
    manifest = GATE / "synthesis.json"
    if not manifest.exists():
        return  # Supplied prebuilt netlist predates synthesis provenance.
    record = json.loads(manifest.read_text())
    if record["inputs"] != synthesis_inputs():
        raise RuntimeError("RTL/configuration or synthesis scripts changed. Run bash run_synthesis.sh first.")
    for name, expected in record["outputs"].items():
        if digest(GATE / name) != expected:
            raise RuntimeError(f"Synthesized gate artifact changed: {name}. Rerun synthesis.")


def synthesize(args):
    require_tools(args.dc_shell)
    db = require_file(args.db.expanduser().resolve())
    model = require_file(args.techlib.expanduser().resolve())
    if args.check:
        print(f"DC executable: {shutil.which(args.dc_shell)}\nNangate timing DB: {db}\nSimulation model: {model}")
        print("File/tool preflight passed. Synthesis and license checkout have not been run.")
        return

    inputs = synthesis_inputs()
    generated_config = write_config()
    folder = unique_run(RUN / "synth")
    for name in ("config", "mapped", "reports", "WORK", "alib"):
        (folder / name).mkdir()
    for relative in inputs:
        destination = folder / "inputs" / relative
        destination.parent.mkdir(parents=True, exist_ok=True)
        shutil.copy2(ROOT / relative, destination)
        if digest(destination) != inputs[relative]:
            raise RuntimeError(f"Input changed while snapshotting: {relative}")
    for header in (ROOT / "config" / "shared").glob("*.vh"):
        shutil.copy2(folder / "inputs" / header.relative_to(ROOT), folder / "config" / header.name)
    shutil.copy2(generated_config / "config.vh", folder / "config" / "config.vh")
    # Keep timing DB and functional cell model with this exact run.
    shutil.copy2(db, folder / "timing.db")
    # The Nangate model declares `timescale 1ns/1ns, which would round its 0.1 ns
    # cell delays to zero; align it with the testbench and Z01X (1ns/1ps).
    (folder / "mapped" / "techLib.v").write_text(re.sub(
        r"`timescale\s+1ns\s*/\s*1ns\b", "`timescale 1ns / 1ps", model.read_text(errors="replace")))
    sources = [folder / "inputs" / path.relative_to(ROOT) for path in source_files("rtl")[:-1]]
    sources.append(folder / "inputs" / "synthDC" / "scripts" / "cvw_wrapper.sv")
    include_dirs = sorted({path.parent for path in (folder / "inputs" / "src").rglob("*") if path.is_file()})
    include_dirs.insert(0, folder / "config")
    (folder / "sources.tcl").write_text(
        "set cvw_sources [list " + " ".join(tcl_path(path) for path in sources) + "]\n" +
        "set cvw_include_dirs [list " + " ".join(tcl_path(path) for path in include_dirs) + "]\n")
    record = {"config": CONFIG, "frequency_mhz": args.freq_mhz, "cores": args.cores,
              "inputs": inputs, "timing_db": str(db), "timing_db_sha256": digest(folder / "timing.db"),
              "simulation_model": str(model), "run": str(folder)}
    (folder / "inputs.json").write_text(json.dumps(record, indent=2) + "\n")
    start = time.monotonic()
    run([args.dc_shell, "-64bit", "-f", folder / "inputs" / "synthDC" / "scripts" / "cvw_synth.tcl"],
        folder, folder / "synthesis.log", extra_env={
            "CVW_SYNTH_RUN": folder, "CVW_SYNTH_DB": folder / "timing.db",
            "CVW_SYNTH_CORES": args.cores, "CVW_SYNTH_MHZ": args.freq_mhz})
    require_file(folder / "SYNTHESIS_OK")
    if re.search(r"^\s*Error(?:\s*:|\s*\[)", (folder / "synthesis.log").read_text(errors="replace"), re.M):
        raise RuntimeError(f"DC reported errors. Active gate files were not replaced; see {folder / 'synthesis.log'}")
    mapped = folder / "mapped"
    output_names = ["wallypipelinedcore" + extension for extension in (".sv", ".ddc", ".sdc", ".sdf")]
    output_names.append("techLib.v")
    for name in output_names:
        if require_file(mapped / name).stat().st_size == 0:
            raise RuntimeError(f"Synthesis output is empty: {name}")
    if not re.search(r"^\s*module\s+wallypipelinedcore_gate\s*\(", (mapped / "wallypipelinedcore.sv").read_text(), re.M):
        raise RuntimeError("Mapped netlist does not export wallypipelinedcore_gate")
    if inputs != synthesis_inputs():
        raise RuntimeError("Inputs changed during synthesis. Active gate files were not replaced; rerun synthesis.")
    record["outputs"] = {name: digest(mapped / name) for name in output_names}
    record["elapsed_seconds"] = time.monotonic() - start
    (folder / "runtime.txt").write_text(f"DC synthesis and output checks: {record['elapsed_seconds']:.3f} seconds\n")
    (mapped / "synthesis.json").write_text(json.dumps(record, indent=2) + "\n")
    # Install only this run's checked outputs. Preserve the full previous
    # gate directory and restore it if the replacement rename fails.
    staged = folder / "install_gate"
    shutil.copytree(mapped, staged)
    ignore_folder(GATE.parent)
    backup = folder / "previous_gate"
    if GATE.exists():
        GATE.rename(backup)
    try:
        staged.rename(GATE)
    except OSError:
        if backup.exists():
            backup.rename(GATE)
        raise
    # Traces of the previous gate design cannot be reused after installation.
    for simulator in ("questa", "vcs"):
        try:
            (RUN / simulator / "latest_gate.json").unlink()
        except FileNotFoundError:
            pass
    print(f"\nSynthesis installed in {GATE}\nDC elapsed seconds: {record['elapsed_seconds']:.3f}\nReports and input snapshots: {folder}")
    if backup.exists():
        print(f"Previous gate files: {backup}")
    print("Next run RTL and gate simulations, then regenerate Z01X coverage.")


def software_inputs(main_file):
    files = [ROOT / "sbst" / "sbst.elf", ROOT / "sbst" / "sbst.hex", main_file]
    files += [path for path in sorted((ROOT / "sbst").iterdir())
              if path.suffix in (".S", ".s", ".c", ".ld", ".h", ".inc") or path.name == "Makefile"]
    return {rel(path): digest(path) for path in files}


def validate_software(firmware):
    if firmware != ROOT / "sbst" / "sbst.hex":
        return  # External images are the caller's responsibility.
    stamp = require_file(ROOT / "sbst" / "sbst.build.json")
    record = json.loads(stamp.read_text())
    if record["inputs"] != software_inputs(ROOT / record["main"]):
        raise RuntimeError("SBST sources or outputs changed. Run bash compile_sbst.sh first.")


def gate_inputs(firmware):
    # Includes program sources so editing without recompiling is also caught.
    files = [NETLIST, LIBRARY, TB / "cvw_tb.sv", Path(__file__).resolve(), firmware,
             DERIVLIST, ROOT / "config" / "rv32e" / "config.vh"]
    files += sorted((ROOT / "config" / "shared").glob("*.vh"))
    files += [path for path in sorted((ROOT / "sbst").iterdir())
              if path.suffix in (".S", ".c", ".ld", ".h") or path.name == "Makefile"]
    # The ELF is not loaded by the HDL, but is kept in sync for disassembly.
    if firmware.with_suffix(".elf").exists():
        files.append(firmware.with_suffix(".elf"))
    # Catch RTL edits made after recording a trace, including for the original
    # prebuilt netlist that has no synthesis provenance yet.
    files += [ROOT / relative for relative in synthesis_inputs()]
    if (GATE / "synthesis.json").exists():
        files.append(GATE / "synthesis.json")
    return {rel(path): digest(path) for path in files}


def unique_run(parent):
    ignore_folder(RUN)
    parent.mkdir(parents=True, exist_ok=True)
    folder = parent / datetime.now(timezone.utc).strftime("%Y%m%dT%H%M%S.%fZ")
    folder.mkdir()
    return folder


def tcl_path(path):
    text = str(path)
    if any(character in text for character in "{}\n\r"):
        raise RuntimeError("Simulator paths cannot contain braces or newlines")
    return "{" + text + "}"


def simulate(args):
    firmware = require_file(args.firmware.resolve())
    validate_software(firmware)
    if args.do_file and args.sim != "questa":
        raise RuntimeError("--do-file is a Questa Tcl feature")
    if args.do_file:
        require_file(args.do_file.resolve())
    # Invalidate the previously selected trace before attempting a new gate run.
    latest = RUN / args.sim / "latest_gate.json"
    if args.mode == "gate":
        try:
            latest.unlink()
        except FileNotFoundError:
            pass
    folder = build(args.mode, args.sim)
    trial = unique_run(RUN / args.sim / args.mode)
    inputs = gate_inputs(firmware) if args.mode == "gate" else None
    # A local snapshot also avoids whitespace parsing of +firmware by HDL %s.
    shutil.copy2(firmware, trial / "firmware.hex")
    if digest(trial / "firmware.hex") != digest(firmware):
        raise RuntimeError("Firmware changed while preparing the trial")
    plusargs = ["+firmware=firmware.hex", f"+max_cycles={args.max_cycles}"]
    if args.mode == "gate":
        plusargs.append("+evcd")
    if args.sim == "questa":
        script = ["onerror {quit -force -code 1}", "onbreak {}", "onfinish stop",
                  "log -r /cvw_tb/dut/*",
                  "log /cvw_tb/clk /cvw_tb/reset /cvw_tb/H* /cvw_tb/address_d /cvw_tb/active_d /cvw_tb/write_d"]
        if args.gui:
            script.append(f"do {tcl_path(TB / 'waves.tcl')}")
        if args.do_file:
            script.append(f"do {tcl_path(args.do_file.resolve())}")
        script.append("run -all")
        if not args.gui:
            script += ["if {[file exists PASS]} {quit -force -code 0} else {quit -force -code 1}"]
        (trial / "simulate.do").write_text("\n".join(script) + "\n")
        run(["vsim", *([] if args.gui else ["-c"]), "-lib", folder / "work",
             "cvw_tb", "-voptargs=+acc", "-wlf", "waves.wlf", "+notimingchecks",
             "+dumpports+nocollapse", *plusargs, "-do", "do simulate.do"],
            trial, trial / "simulation.log")
    else:
        run([folder / "simv", *(["-gui"] if args.gui else []), *plusargs],
            trial, trial / "simulation.log")
    require_file(trial / "PASS")
    if args.mode == "gate" and not args.gui and not args.do_file:
        require_file(trial / "core.evcd")
        if (trial / "core.evcd").stat().st_size == 0:
            raise RuntimeError("Gate simulator produced an empty EVCD")
        if inputs != gate_inputs(firmware):
            raise RuntimeError("Inputs changed during the simulation. Rerun before fault simulation.")
        record = {"simulator": args.sim, "firmware": rel(firmware), "inputs": inputs,
                  "trace": rel(trial / "core.evcd"), "trace_sha256": digest(trial / "core.evcd")}
        latest.write_text(json.dumps(record, indent=2) + "\n")
    print(f"\nTrial passed. Artifacts: {trial}")


def verify_good_machine(log):
    """Some Z01X releases report replay mismatches with exit status zero."""
    for line in log.read_text(errors="replace").splitlines():
        if not re.search(r"mismatch|miscompare", line, re.I):
            continue
        if re.search(r"\+vcd\+", line, re.I):
            continue
        if re.search(r"\b(no|zero|0)\s+(\w+\s+){0,3}(mismatch|miscompare)", line, re.I):
            continue
        if re.search(r"(mismatch\w*|miscompare\w*)\D*[:=]\s*0\b", line, re.I):
            continue
        raise RuntimeError(f"Review GM replay before fault grading; see {log}: {line}")


def fault_simulate(args):
    require_tools("zoix", "fmsh", "fault_report")
    validate_synthesized_gate()
    latest = require_file(RUN / args.sim / "latest_gate.json")
    record = json.loads(latest.read_text())
    firmware = ROOT / record["firmware"]  # an absolute path stays absolute
    if record["inputs"] != gate_inputs(firmware):
        raise RuntimeError("Gate trace is stale. Recompile SBST and rerun the gate simulation.")
    trace = ROOT / record["trace"]
    if digest(trace) != record["trace_sha256"]:
        raise RuntimeError("Gate trace changed after simulation; rerun the gate simulation.")
    sff = require_file(args.faults.resolve())
    folder = unique_run(RUN / "zoix")
    shutil.copy2(trace, folder / "stimulus.evcd")
    shutil.copy2(sff, folder / "faults.sff")
    shutil.copy2(ZOIX / "strobe.sv", folder / "strobe.sv")
    shutil.copy2(ZOIX / "fsim.fmsh", folder / "fsim.fmsh")
    shutil.copy2(latest, folder / "gate_inputs.json")
    # Pass paths directly as argv entries. This Z01X release retains quote
    # characters around a -v path in a filelist as part of the filename.
    start = time.monotonic()
    run(["zoix", "-v", LIBRARY, NETLIST, "strobe.sv", "+timescale+override+1ns/1ps",
         "+top+wallypipelinedcore_gate+strobe", "+sv", "+notimingchecks",
         "+define+functional", "+define+ZOIX", "+suppress+cell", "+delay_mode_fault",
         "+verbose+undriven", "-l", "zoix_compile.log"], folder, folder / "compile.log")
    run([folder / "zoix.sim", "+vcd+file+stimulus.evcd",
         "+vcd+dut+wallypipelinedcore_gate+cvw_tb.dut", "+vcd+verify",
         "+vcd+verbose", "+vcd+limit+mismatch+1", "-l", "zoix_logic.log"],
        folder, folder / "good_machine.log")
    verify_good_machine(folder / "good_machine.log")
    verify_good_machine(require_file(folder / "zoix_logic.log"))
    run(["fmsh", "-load", "fsim.fmsh"], folder, folder / "fault_simulation.log")
    run(["fault_report", "+group+detail"], folder, folder / "fault_report_output.log")
    require_file(folder / "cvw_coverage.sff")
    elapsed = time.monotonic() - start
    (folder / "runtime.txt").write_text(f"Compile + replay + fault simulation + report: {elapsed:.3f} seconds\n")
    print(f"\nFault flow complete in {elapsed:.3f}s. Reports: {folder}")


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    sub = parser.add_subparsers(dest="command")
    build_parser = sub.add_parser("build")
    build_parser.add_argument("mode", choices=("rtl", "gate", "all"), nargs="?", default="all")
    sim_parser = sub.add_parser("sim")
    sim_parser.add_argument("mode", choices=("rtl", "gate"))
    sim_parser.add_argument("--gui", action="store_true")
    sim_parser.add_argument("--firmware", type=Path, default=ROOT / "sbst" / "sbst.hex")
    sim_parser.add_argument("--max-cycles", type=int, default=100000)
    sim_parser.add_argument("--do-file", type=Path, help="Questa Tcl to execute before run -all")
    fault_parser = sub.add_parser("fault")
    fault_parser.add_argument("--faults", type=Path, default=ZOIX / "faults.sff")
    stamp_parser = sub.add_parser("stamp", help="Internal Makefile completion record")
    stamp_parser.add_argument("--main", type=Path, required=True)
    synth_parser = sub.add_parser("synth", help="Synthesize and install the configured core with Design Compiler")
    synth_parser.add_argument("--cores", type=int, default=1)
    synth_parser.add_argument("--freq-mhz", type=float, default=1500.0)
    synth_parser.add_argument("--dc-shell", default=os.environ.get("DC_SHELL", "dc_shell-xg-t"))
    synth_parser.add_argument("--db", type=Path, default=find_library("CVW_SYNTH_DB", DB_NAME))
    synth_parser.add_argument("--techlib", type=Path,
                              default=find_library("LIBRARY_SIM_PATH", MODEL_NAME, preferred=LIBRARY))
    synth_parser.add_argument("--check", action="store_true", help="Check tool/library paths without running synthesis")
    sub.add_parser("clean", help="Remove run/ and the compiled SBST; sources and gate/ are kept")
    for command_parser in (build_parser, sim_parser, fault_parser):
        command_parser.add_argument("--sim", choices=("questa", "vcs"), default=os.environ.get("SIM", "questa"))
    args = parser.parse_args()
    if args.command is None:
        parser.error("a command is required: build, sim, fault, synth, clean, or stamp")
    if args.command == "clean":
        shutil.rmtree(RUN, ignore_errors=True)
        run(["make", "-C", ROOT / "sbst", "clean"], ROOT, Path(os.devnull))
        return
    if args.command == "synth":
        if args.cores <= 0:
            parser.error("--cores must be positive")
        if not math.isfinite(args.freq_mhz) or args.freq_mhz <= 0:
            parser.error("--freq-mhz must be finite and positive")
        synthesize(args)
        return
    if args.command == "stamp":
        main_file = args.main.resolve()
        record = {"main": rel(main_file), "inputs": software_inputs(main_file)}
        (ROOT / "sbst" / "sbst.build.json").write_text(json.dumps(record, indent=2) + "\n")
        return
    if args.sim not in ("questa", "vcs"):
        parser.error("SIM must be questa or vcs")
    if args.command == "build":
        for mode in (("rtl", "gate") if args.mode == "all" else (args.mode,)):
            build(mode, args.sim)
    elif args.command == "sim":
        if args.max_cycles <= 0:
            parser.error("--max-cycles must be positive")
        simulate(args)
    else:
        fault_simulate(args)


if __name__ == "__main__":
    try:
        main()
    except (RuntimeError, OSError, ValueError, KeyError) as error:
        print(f"\nERROR: {error}", file=sys.stderr)
        sys.exit(1)
    except KeyboardInterrupt:
        sys.exit(130)
